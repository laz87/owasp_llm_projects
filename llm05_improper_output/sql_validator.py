"""
SQL Validator — LLM05: Improper Output Handling

Validates and sanitizes SQL queries generated by an LLM before execution.
Uses query whitelisting and pattern matching to prevent SQL injection.
"""

import re
from dataclasses import dataclass
from enum import Enum


class QueryType(Enum):
    """Allowed SQL query types."""
    SELECT = "SELECT"
    INSERT = "INSERT"
    UPDATE = "UPDATE"
    DELETE = "DELETE"


@dataclass
class ValidationResult:
    """Result of validating a SQL query."""
    is_safe: bool
    query_type: QueryType | None = None
    issues: list[str] = None

    def __post_init__(self):
        if self.issues is None:
            self.issues = []


# ---------------------------------------------------------------------------
# Dangerous SQL Patterns
# ---------------------------------------------------------------------------

DANGEROUS_PATTERNS = [
    {
        "name": "DROP statement",
        "pattern": r"(?i)\bDROP\s+(TABLE|DATABASE|INDEX|COLUMN)\b",
        "severity": "critical",
    },
    {
        "name": "ALTER statement",
        "pattern": r"(?i)\bALTER\s+(TABLE|DATABASE)\b",
        "severity": "critical",
    },
    {
        "name": "CREATE statement",
        "pattern": r"(?i)\bCREATE\s+(TABLE|DATABASE|INDEX|USER)\b",
        "severity": "critical",
    },
    {
        "name": "TRUNCATE statement",
        "pattern": r"(?i)\bTRUNCATE\s+TABLE\b",
        "severity": "critical",
    },
    {
        "name": "UNION injection",
        "pattern": r"(?i)\bUNION\s+(ALL\s+)?SELECT\b",
        "severity": "high",
    },
    {
        "name": "Comment injection",
        "pattern": r"(--|;|/\*)",
        "severity": "high",
    },
    {
        "name": "Semicolon chaining",
        "pattern": r";\s*(DROP|ALTER|CREATE|TRUNCATE|INSERT|UPDATE|DELETE)\b",
        "severity": "critical",
    },
    {
        "name": "OR 1=1 injection",
        "pattern": r"(?i)\bOR\s+1\s*=\s*1\b",
        "severity": "high",
    },
    {
        "name": "String concatenation injection",
        "pattern": r"(?i)(\bOR\b\s+['\"]\w+['\"]\s*=\s*['\"]\w+['\"])",
        "severity": "high",
    },
    {
        "name": "EXEC/EXECUTE command",
        "pattern": r"(?i)\bEXEC(UTE)?\s*\(",
        "severity": "critical",
    },
    {
        "name": "xp_cmdshell",
        "pattern": r"(?i)\bxp_cmdshell\b",
        "severity": "critical",
    },
    {
        "name": "LOAD_FILE",
        "pattern": r"(?i)\bLOAD_FILE\s*\(",
        "severity": "high",
    },
    {
        "name": "INTO OUTFILE",
        "pattern": r"(?i)\bINTO\s+(OUTFILE|DUMPFILE)\b",
        "severity": "high",
    },
]


# ---------------------------------------------------------------------------
# Allowed Tables and Columns
# ---------------------------------------------------------------------------

ALLOWED_TABLES = {"users", "products", "orders", "categories"}
ALLOWED_COLUMNS = {
    "users": {"id", "name", "email", "created_at"},
    "products": {"id", "name", "price", "category", "stock"},
    "orders": {"id", "user_id", "product_id", "quantity", "total", "status"},
    "categories": {"id", "name", "description"},
}


class SQLValidator:
    """
    Validate SQL queries generated by an LLM.

    Usage:
        validator = SQLValidator(allowed_query_types={QueryType.SELECT})
        result = validator.validate(sql_query)
        if not result.is_safe:
            print(f"Blocked: {result.issues}")
    """

    def __init__(self, allowed_query_types: set[QueryType] | None = None):
        """
        Args:
            allowed_query_types: Set of allowed query types. If None, all are allowed.
        """
        self.allowed_types = allowed_query_types or {QueryType.SELECT}
        self.compiled_patterns = []
        for pat_def in DANGEROUS_PATTERNS:
            self.compiled_patterns.append({
                "name": pat_def["name"],
                "regex": re.compile(pat_def["pattern"]),
                "severity": pat_def["severity"],
            })

    def validate(self, query: str) -> ValidationResult:
        """
        Validate a SQL query for safety.

        Args:
            query: The SQL query to validate.

        Returns:
            ValidationResult with safety status and issues.
        """
        issues = []
        query_type = None

        # Check for dangerous patterns
        for pat in self.compiled_patterns:
            if pat["regex"].search(query):
                issues.append(f"[{pat['severity'].upper()}] {pat['name']} detected")

        # Determine query type
        stripped = query.strip().upper()
        for qt in QueryType:
            if stripped.startswith(qt.value):
                query_type = qt
                break

        # Check if query type is allowed
        if query_type and query_type not in self.allowed_types:
            issues.append(f"[HIGH] Query type '{query_type.value}' is not allowed")

        # Check table references
        tables_found = self._extract_tables(query)
        for table in tables_found:
            if table.lower() not in ALLOWED_TABLES:
                issues.append(f"[MEDIUM] Table '{table}' is not in allowed list")

        # Check for unparameterized values (basic check)
        if query_type == QueryType.SELECT:
            # Look for string values without parameterization
            if re.search(r"(?i)\bWHERE\b.*['\"][^'\"]*['\"]", query):
                issues.append("[LOW] Consider using parameterized queries instead of string values")

        is_safe = len(issues) == 0

        return ValidationResult(
            is_safe=is_safe,
            query_type=query_type,
            issues=issues,
        )

    def _extract_tables(self, query: str) -> list[str]:
        """Extract table names from a SQL query."""
        tables = []
        # FROM clause
        from_matches = re.findall(r"(?i)\bFROM\s+(\w+)", query)
        tables.extend(from_matches)
        # JOIN clause
        join_matches = re.findall(r"(?i)\bJOIN\s+(\w+)", query)
        tables.extend(join_matches)
        # WHERE table.column pattern
        where_matches = re.findall(r"(?i)\bWHERE\s+(\w+)\.\w+", query)
        tables.extend(where_matches)
        return tables

    def validate_and_report(self, query: str) -> str:
        """Validate and return a formatted report."""
        result = self.validate(query)

        if result.is_safe:
            return f"✓ Query is safe. Type: {result.query_type.value if result.query_type else 'unknown'}"

        lines = [f"✗ Query is UNSAFE. {len(result.issues)} issue(s) found:"]
        for issue in result.issues:
            lines.append(f"  - {issue}")
        return "\n".join(lines)
